import { useEffect, useState } from "react";
import axios from "axios";

function AIRecommendations() {

  const [recommendations, setRecommendations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    fetchRecommendations();
  }, []);

  const fetchRecommendations = async () => {

    try {

      const response = await axios.get(
        "http://localhost:8081/api/recommendations/jobs/1/syllabus/4"
      );

      setRecommendations(response.data);

    } catch (error) {

      console.error(error);
      setError("Failed to load AI recommendations.");

    } finally {

      setLoading(false);

    }
  };

  if (loading) {
    return (
      <div className="page-content">
        <h1>AI Recommendations</h1>
        <p>Generating AI recommendations...</p>
      </div>
    );
  }

  if (error) {
    return (
      <div className="page-content">
        <h1>AI Recommendations</h1>
        <p className="error-message">{error}</p>
      </div>
    );
  }

  return (
    <div className="page-content">

      <div className="page-header">

        <h1>AI Recommendations</h1>

        <p>
          Personalized recommendations generated by
          AI based on industry skill gaps.
        </p>

      </div>

      <div className="card">

        <h2>AI-Powered Recommendations</h2>

        {recommendations.length === 0 ? (

          <p>No recommendations available.</p>

        ) : (

          recommendations.map((item, index) => (

            <div
              key={index}
              className="recommendation-card"
            >

              <h3>
                {item.skill}
              </h3>

              <p>
                <strong>Status:</strong>{" "}
                {item.status}
              </p>

              <p>
                <strong>Priority:</strong>{" "}
                {item.priority}
              </p>

              <p>
                <strong>AI Analysis:</strong>
                <br />
                {item.explanation}
              </p>

              <p>
                <strong>Curriculum Recommendation:</strong>
                <br />
                {item.curriculumRecommendation}
              </p>

              <p>
                <strong>Student Recommendation:</strong>
                <br />
                {item.studentRecommendation}
              </p>

            </div>

          ))

        )}

      </div>

    </div>
  );
}

export default AIRecommendations;