-- V6 (Phase 6.4): NBA outcomes.
-- PO/PSO belong to a program; CO belongs to a syllabus subject; CO-PO mapping level 1..3.

CREATE TABLE IF NOT EXISTS program_outcome (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id   BIGINT NOT NULL REFERENCES program(id) ON DELETE CASCADE,
    kind         VARCHAR(10) NOT NULL DEFAULT 'PO',   -- PO or PSO
    code         VARCHAR(20) NOT NULL,                -- PO1 … PO12, PSO1 …
    title        VARCHAR(255) NOT NULL,
    description  TEXT,
    sort_order   INT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_program_outcome_code ON program_outcome(program_id, code);

CREATE TABLE IF NOT EXISTS course_outcome (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id   BIGINT NOT NULL REFERENCES subject(id) ON DELETE CASCADE,
    code         VARCHAR(20) NOT NULL,                -- CO1 …
    description  TEXT NOT NULL,
    bloom_level  VARCHAR(20),                         -- Remember … Create (optional)
    sort_order   INT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_course_outcome_code ON course_outcome(subject_id, code);

CREATE TABLE IF NOT EXISTS co_po_mapping (
    course_outcome_id   BIGINT NOT NULL REFERENCES course_outcome(id) ON DELETE CASCADE,
    program_outcome_id  BIGINT NOT NULL REFERENCES program_outcome(id) ON DELETE CASCADE,
    level               SMALLINT NOT NULL CHECK (level BETWEEN 1 AND 3),
    PRIMARY KEY (course_outcome_id, program_outcome_id)
);
