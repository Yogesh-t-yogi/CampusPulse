-- V3 (Phase 6.2): colleges, departments and programs; users, syllabi and catalog jobs
-- belong to a college. Existing data moves into "Default College" / "General".

CREATE TABLE institution (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    code        VARCHAR(50)  NOT NULL UNIQUE,
    city        VARCHAR(255),
    created_at  TIMESTAMP(6) NOT NULL DEFAULT now()
);

CREATE TABLE department (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT NOT NULL REFERENCES institution(id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    code            VARCHAR(50)  NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL DEFAULT now(),
    UNIQUE (institution_id, code)
);

CREATE TABLE program (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id       BIGINT NOT NULL REFERENCES department(id) ON DELETE CASCADE,
    name                VARCHAR(255) NOT NULL,   -- e.g. B.E. Computer Science and Engineering
    degree              VARCHAR(50)  NOT NULL,   -- e.g. BE, BTECH, MCA, MBA
    code                VARCHAR(50)  NOT NULL,   -- e.g. CSE
    regulation          VARCHAR(50),             -- e.g. 2021
    duration_semesters  INT NOT NULL DEFAULT 8,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT now(),
    UNIQUE (department_id, code, regulation)
);

ALTER TABLE app_user ADD COLUMN institution_id BIGINT REFERENCES institution(id);
ALTER TABLE app_user ADD COLUMN department_id  BIGINT REFERENCES department(id) ON DELETE SET NULL;
ALTER TABLE app_user ADD COLUMN program_id     BIGINT REFERENCES program(id) ON DELETE SET NULL;

ALTER TABLE syllabus ADD COLUMN institution_id BIGINT REFERENCES institution(id);
ALTER TABLE syllabus ADD COLUMN department_id  BIGINT REFERENCES department(id) ON DELETE SET NULL;
ALTER TABLE syllabus ADD COLUMN program_id     BIGINT REFERENCES program(id) ON DELETE SET NULL;
ALTER TABLE syllabus ADD COLUMN semester       INT;

-- Catalog jobs: NULL = global catalog (super admin), set = that college's catalog.
ALTER TABLE job_posting ADD COLUMN institution_id BIGINT REFERENCES institution(id) ON DELETE CASCADE;

-- Default college for everything that already exists.
INSERT INTO institution (name, code, city) VALUES ('Default College', 'DEFAULT', NULL);
INSERT INTO department (institution_id, name, code)
    SELECT id, 'General', 'GEN' FROM institution WHERE code = 'DEFAULT';

UPDATE app_user SET
    institution_id = (SELECT id FROM institution WHERE code = 'DEFAULT'),
    department_id  = (SELECT d.id FROM department d JOIN institution i ON i.id = d.institution_id
                      WHERE i.code = 'DEFAULT' AND d.code = 'GEN');

UPDATE syllabus s SET
    institution_id = u.institution_id,
    department_id  = u.department_id
FROM app_user u
WHERE u.id = s.user_id;

CREATE INDEX idx_app_user_institution ON app_user(institution_id);
CREATE INDEX idx_syllabus_institution ON syllabus(institution_id);
CREATE INDEX idx_department_institution ON department(institution_id);
CREATE INDEX idx_program_department ON program(department_id);
