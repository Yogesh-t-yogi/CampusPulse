-- V3 (Phase 6.2): colleges, departments and programs; users, syllabi and catalog jobs
-- belong to a college. Existing data moves into "Default College" / "General".
--
-- Written to be safe on a database where Hibernate (ddl-auto=update) already created
-- some of these tables/columns before Flyway ran: everything is "if not exists", and
-- foreign keys are added only when missing.

CREATE TABLE IF NOT EXISTS institution (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    code        VARCHAR(50)  NOT NULL,
    city        VARCHAR(255),
    created_at  TIMESTAMP(6) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_institution_code ON institution(code);

CREATE TABLE IF NOT EXISTS department (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT NOT NULL,
    name            VARCHAR(255) NOT NULL,
    code            VARCHAR(50)  NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_department_code ON department(institution_id, code);

CREATE TABLE IF NOT EXISTS program (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id       BIGINT NOT NULL,
    name                VARCHAR(255) NOT NULL,   -- e.g. B.E. Computer Science and Engineering
    degree              VARCHAR(50)  NOT NULL,   -- e.g. BE, BTECH, MCA, MBA
    code                VARCHAR(50)  NOT NULL,   -- e.g. CSE
    regulation          VARCHAR(50),             -- e.g. 2021
    duration_semesters  INT NOT NULL DEFAULT 8,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_program_code ON program(department_id, code, regulation);

ALTER TABLE app_user ADD COLUMN IF NOT EXISTS institution_id BIGINT;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS department_id  BIGINT;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS program_id     BIGINT;

ALTER TABLE syllabus ADD COLUMN IF NOT EXISTS institution_id BIGINT;
ALTER TABLE syllabus ADD COLUMN IF NOT EXISTS department_id  BIGINT;
ALTER TABLE syllabus ADD COLUMN IF NOT EXISTS program_id     BIGINT;
ALTER TABLE syllabus ADD COLUMN IF NOT EXISTS semester       INT;

-- Catalog jobs: NULL = global catalog (platform admin), set = that college's catalog.
ALTER TABLE job_posting ADD COLUMN IF NOT EXISTS institution_id BIGINT;

-- Defaults where Hibernate created the columns without them.
ALTER TABLE institution ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE department ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE program ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE program ALTER COLUMN duration_semesters SET DEFAULT 8;

-- Foreign keys (only when missing).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_department_institution') THEN
        ALTER TABLE department ADD CONSTRAINT fk_department_institution
            FOREIGN KEY (institution_id) REFERENCES institution(id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_program_department') THEN
        ALTER TABLE program ADD CONSTRAINT fk_program_department
            FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_app_user_institution') THEN
        ALTER TABLE app_user ADD CONSTRAINT fk_app_user_institution
            FOREIGN KEY (institution_id) REFERENCES institution(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_app_user_department') THEN
        ALTER TABLE app_user ADD CONSTRAINT fk_app_user_department
            FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_app_user_program') THEN
        ALTER TABLE app_user ADD CONSTRAINT fk_app_user_program
            FOREIGN KEY (program_id) REFERENCES program(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_syllabus_institution') THEN
        ALTER TABLE syllabus ADD CONSTRAINT fk_syllabus_institution
            FOREIGN KEY (institution_id) REFERENCES institution(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_syllabus_department') THEN
        ALTER TABLE syllabus ADD CONSTRAINT fk_syllabus_department
            FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_syllabus_program') THEN
        ALTER TABLE syllabus ADD CONSTRAINT fk_syllabus_program
            FOREIGN KEY (program_id) REFERENCES program(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_job_posting_institution') THEN
        ALTER TABLE job_posting ADD CONSTRAINT fk_job_posting_institution
            FOREIGN KEY (institution_id) REFERENCES institution(id) ON DELETE CASCADE;
    END IF;
END $$;

-- Default college + department (only if missing).
INSERT INTO institution (name, code, city, created_at)
SELECT 'Default College', 'DEFAULT', NULL, now()
WHERE NOT EXISTS (SELECT 1 FROM institution WHERE code = 'DEFAULT');

INSERT INTO department (institution_id, name, code, created_at)
SELECT i.id, 'General', 'GEN', now()
FROM institution i
WHERE i.code = 'DEFAULT'
  AND NOT EXISTS (SELECT 1 FROM department d WHERE d.institution_id = i.id AND d.code = 'GEN');

-- Anyone without a college goes to Default College / General.
UPDATE app_user SET
    institution_id = (SELECT id FROM institution WHERE code = 'DEFAULT'),
    department_id  = (SELECT d.id FROM department d JOIN institution i ON i.id = d.institution_id
                      WHERE i.code = 'DEFAULT' AND d.code = 'GEN')
WHERE institution_id IS NULL;

-- Syllabi without a college take their owner's.
UPDATE syllabus s SET
    institution_id = u.institution_id,
    department_id  = COALESCE(s.department_id, u.department_id)
FROM app_user u
WHERE u.id = s.user_id
  AND s.institution_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_app_user_institution ON app_user(institution_id);
CREATE INDEX IF NOT EXISTS idx_syllabus_institution ON syllabus(institution_id);
CREATE INDEX IF NOT EXISTS idx_department_institution ON department(institution_id);
CREATE INDEX IF NOT EXISTS idx_program_department ON program(department_id);
