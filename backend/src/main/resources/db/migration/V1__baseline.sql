-- V1: CampusPulse schema as of v2 change 027 (2026-11-10).
-- Runs only on an EMPTY database. Existing databases are marked as V1 by
-- spring.flyway.baseline-on-migrate and skip this file; V2 brings them up to date.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS app_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS syllabus (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT REFERENCES app_user(id),
    name                VARCHAR(255) NOT NULL,
    file_name           VARCHAR(255),
    extracted_text      TEXT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    processing_status   VARCHAR(30),
    processing_message  TEXT
);

CREATE TABLE IF NOT EXISTS subject (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    code         VARCHAR(255),
    syllabus_id  BIGINT NOT NULL REFERENCES syllabus(id)
);

CREATE TABLE IF NOT EXISTS unit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    unit_number  INTEGER,
    subject_id   BIGINT NOT NULL REFERENCES subject(id)
);

CREATE TABLE IF NOT EXISTS topic (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    description  TEXT,
    unit_id      BIGINT NOT NULL REFERENCES unit(id)
);

CREATE TABLE IF NOT EXISTS topic_embedding (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id   BIGINT NOT NULL UNIQUE REFERENCES topic(id),
    embedding  vector(384) NOT NULL,
    model      VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS job_posting (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255) NOT NULL,
    company        VARCHAR(255),
    location       VARCHAR(255),
    description    TEXT,
    source         VARCHAR(255),
    job_url        VARCHAR(255),
    owner_user_id  BIGINT REFERENCES app_user(id),
    created_at     TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS job_required_skill (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill           VARCHAR(255) NOT NULL,
    job_posting_id  BIGINT NOT NULL REFERENCES job_posting(id)
);

CREATE TABLE IF NOT EXISTS skill_embedding (
    skill_key   TEXT PRIMARY KEY,
    embedding   vector(384) NOT NULL,
    model       VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS analysis_result (
    id                    BIGSERIAL PRIMARY KEY,
    syllabus_id           BIGINT NOT NULL REFERENCES syllabus(id) ON DELETE CASCADE,
    job_id                BIGINT NOT NULL REFERENCES job_posting(id) ON DELETE CASCADE,
    report_json           TEXT,
    recommendations_json  TEXT,
    algo_version          INT NOT NULL DEFAULT 1,
    updated_at            TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (syllabus_id, job_id)
);
